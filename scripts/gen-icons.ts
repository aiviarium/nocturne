// Reads the 48 Nocturne core icons from icons/*.svg and writes src/components/icon-data.ts.
// Run with `bun run gen:icons` after adding or changing an icon. Each SVG is drawn on the 16px grid with a 1.5
// stroke; only its path data is kept.
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const dir = join(import.meta.dir, "../icons")
const out = join(import.meta.dir, "../src/components/icon-data.ts")
const names = readdirSync(dir)
  .filter((f) => f.endsWith(".svg"))
  .map((f) => f.replace(/\.svg$/, ""))
  .sort()

const lines: string[] = []
for (const name of names) {
  const svg = readFileSync(join(dir, `${name}.svg`), "utf8")
  const d = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1])
  if (d.length === 0) throw new Error(`${name}.svg has no path`)
  lines.push(`  ${JSON.stringify(name)}: ${JSON.stringify(d.join(" "))},`)
}
writeFileSync(
  out,
  `// Generated by scripts/gen-icons.ts from icons/*.svg. Do not edit.\n// Path data on the 16px grid, drawn with a 1.5 stroke by the Icon component.\nexport const ICON_PATHS = {\n${lines.join("\n")}\n} as const\n\nexport type IconName = keyof typeof ICON_PATHS\n`,
)
console.log(`wrote ${names.length} icons`)
