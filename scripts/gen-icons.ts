// Writes src/components/icon-data.ts and icons/*.svg from scripts/icons.ts and the `lucide` package.
// Run with `bun run gen:icons` after adding or changing a name. Every icon is a Lucide icon on its 24px grid.
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import * as lucide from "lucide"
import { EXTRA, NAMES } from "./icons"

type Node = ReadonlyArray<readonly [string, Record<string, string | number>]>

const root = join(import.meta.dir, "..")
const out = join(root, "src/components/icon-data.ts")
const svgDir = join(root, "icons")

const icons: Record<string, Node> = {}
for (const [name, source] of Object.entries(NAMES)) {
  const node = (lucide as unknown as Record<string, Node | undefined>)[source]
  if (node === undefined) throw new Error(`lucide has no ${source} for ${name}`)
  icons[name] = node.map(
    ([tag, attrs]) =>
      [tag, Object.fromEntries(Object.entries(attrs).filter(([key]) => key !== "key"))] as const,
  )
}
for (const [name, node] of Object.entries(EXTRA)) icons[name] = node

const names = Object.keys(icons).sort()
const body = names.map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(icons[name])},`).join("\n")
writeFileSync(
  out,
  `// Generated by scripts/gen-icons.ts from scripts/icons.ts and the lucide package (ISC licence, lucide.dev).\n// Do not edit. Each icon is a list of [tag, attributes] on Lucide's 24px grid.\nexport const ICON_NODES = {\n${body}\n} as const satisfies Record<string, ReadonlyArray<readonly [string, Readonly<Record<string, string | number>>]>>\n\nexport type IconName = keyof typeof ICON_NODES\n`,
)

// The SVG files are what the site's icon grid shows.
mkdirSync(svgDir, { recursive: true })
for (const file of readdirSync(svgDir)) if (file.endsWith(".svg")) rmSync(join(svgDir, file))
const attr = (attrs: Record<string, string | number>) =>
  Object.entries(attrs)
    .map(([key, value]) => `${key}="${value}"`)
    .join(" ")
for (const name of names) {
  const shapes = icons[name]!.map(([tag, attrs]) => `  <${tag} ${attr(attrs)}/>`).join("\n")
  writeFileSync(
    join(svgDir, `${name}.svg`),
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">\n${shapes}\n</svg>\n`,
  )
}
console.log(`wrote ${names.length} icons`)
